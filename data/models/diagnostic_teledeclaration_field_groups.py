def get_teledeclaration_field_groups(year, label):
    year = int(year) if year else None
    if year not in TELEDECLARATION_FIELD_GROUPS:
        raise ValueError(f"Field 'year' expected one of {list(TELEDECLARATION_FIELD_GROUPS.keys())} but got '{year}'.")
    if label == "APPRO_LABELS":
        return (
            TELEDECLARATION_FIELD_GROUPS[year]["APPRO_LABELS_EGALIM"]
            + TELEDECLARATION_FIELD_GROUPS[year]["APPRO_LABELS_NON_EGALIM"]
        )
    elif label == "APPRO_LABELS_ALL":
        return (
            TELEDECLARATION_FIELD_GROUPS[year]["APPRO_LABELS_EGALIM"]
            + TELEDECLARATION_FIELD_GROUPS[year]["APPRO_LABELS_NON_EGALIM"]
            + ["bio_dont_commerce_equitable"]
            + TELEDECLARATION_FIELD_GROUPS[year]["APPRO_LABELS_ORIGINE"]
            + ["circuit_court", "local"]
        )
    elif label not in TELEDECLARATION_FIELD_GROUPS[year]:
        valid_labels = list(TELEDECLARATION_FIELD_GROUPS[year].keys()) + ["APPRO_LABELS", "APPRO_LABELS_ALL"]
        raise ValueError(f"Field 'label' expected one of {valid_labels} but got '{label}'.")
    return TELEDECLARATION_FIELD_GROUPS[year][label]
